const CLOSINGS = [
  'Great job! Keep speaking every day! 💪',
  'Well done! Say these lines again tonight. 💪',
  'Nice work! You are getting better every day. 💪'
];

/** Lesson JSON for Beginner `day` (1-30), or null outside the foundation plan. */
function buildBeginnerFallbackJson(day, conversationPrefix) {
  const lesson = LESSONS[day];
  const plan = BEGINNER_FOUNDATION_TOPICS[day - 1];
  if (!lesson || !plan) return null;
  return {
    title: plan.title,
    scenarioType: lesson.focus,
    conversation: `${conversationPrefix}\n\n${lesson.lines.map((l, i) => `${i % 2 ? 'B' : 'A'}: ${l}`).join('\n')}`,
    explanation: `${plan.grammarFocus.split(' / ').join('\n')}\nPractice these with your own words.`,
    guidedSpeakingPrompts: [...lesson.speak],
    newVocabulary: lesson.vocab.map(([word, meaning, example]) => ({ word, meaning, example })),
    microPractice: { q1: lesson.practice[0], q2: lesson.practice[1] },
    confidenceLine: CLOSINGS[day % CLOSINGS.length]
  };
}

module.exports = { buildBeginnerFallbackJson };
